const assert = require('node:assert/strict');
const M = require('./pds-model.js');
let state = M.empty();
const apply = (type, data) => { const result = M.apply(state, { type, data }, '2026-11-18T03:00:00.000Z'); state = result.state; return result.id; };
const planData = { title: '<script>plan()</script>', start_date: '2026-11-01', end_date: '2026-11-30', priority: '2', success_criteria: 'Original criteria', estimated_minutes: '120' };
const plan = apply('plan.save', planData);
apply('plan.save', { ...planData, id: plan, title: 'Changed plan' });
assert.equal(state.versions[0].snapshot.title, planData.title);
assert.equal(state.versions.length, 2);
const taskData = { plan_id: plan, title: 'Test task', due_date: '2026-11-17', priority: '2', tags: 'study, python', estimated_minutes: '30' };
const task = apply('task.save', taskData);
const other = apply('task.save', { ...taskData, title: 'Future task', due_date: '2026-11-20', estimated_minutes: '20' });
const removed = apply('task.save', { ...taskData, title: 'Deleted task', estimated_minutes: '900' });
apply('delete', { kind: 'task', id: removed });
for (let i = 0; i < 8; i++) apply('task.complete', { task_id: task, completed: '1' });
assert.equal(state.completions.length, 1);
assert.equal(M.summary(state, plan, '', '', '2026-11-18').values.completed, 1);
assert.equal(M.summary(state, plan, '', '', '2026-11-18').values.delayed, 0);
apply('task.complete', { task_id: task, completed: '0' });
assert.equal(state.completions.length, 0);
assert.equal(M.summary(state, plan, '', '', '2026-11-18').values.delayed, 1);
apply('task.complete', { task_id: task, completed: '1' });
const exec = { task_id: task, started_at: '2026-11-18T09:00', ended_at: '2026-11-18T09:45', blocked_reason: '<img src=x onerror=alert(1)>', idempotency_key: 'b99a5f3c-82f4-4bd1-aa8f-52fbbfb64b03' };
const record = apply('execution.save', exec);
assert.equal(apply('execution.save', exec), record);
assert.equal(state.executions.length, 1);
assert.equal(state.executions[0].started_at, '2026-11-18T00:00:00.000Z');
assert.equal(state.tasks.find(t => t.id === task).estimated_minutes, 30);
assert.equal(state.plans[0].estimated_minutes, 120);
assert.deepEqual(M.summary(state, plan, '', '', '2026-11-18').values, { planned: 2, completed: 1, delayed: 0, blocked: 1, estimated: 50, actual: 45, difference: -5 });
assert(M.summary(state, plan, '2026-12-01', '2026-12-31').values.actual === 0);
apply('execution.save', { ...exec, id: record, ended_at: '2026-11-18T09:20' });
assert.equal(M.summary(state, plan).values.actual, 20);
apply('task.save', { ...taskData, id: other, title: 'Edited task', priority: '1' });
assert.equal(state.tasks.find(t => t.id === other).priority, 1);
const review = apply('review.save', { plan_id: plan, from_date: '2026-11-01', to_date: '2026-11-30', reflection: 'Lessons', improvement: 'Start earlier' });
const next = apply('plan.next', { review_id: review, title: 'Next', start_date: '2026-12-01', end_date: '2026-12-31' });
assert.equal(apply('plan.next', { review_id: review }), next);
assert.equal(M.find(state, 'plans', next).improvement, 'Start earlier');
assert.deepEqual(M.validate(JSON.parse(JSON.stringify(state))), state);
assert.equal(M.today(new Date('2026-11-17T15:01:00Z')), '2026-11-18');
for (const bad of ['2026-02-30', 'not-date', '2026-1-1']) assert.throws(() => M.date(bad));
assert.throws(() => apply('execution.save', { ...exec, ended_at: '2026-11-18T08:00' }));
assert.throws(() => apply('execution.save', { ...exec, started_at: '2026-11-18T09:00:30' }));
assert.throws(() => apply('plan.save', { ...planData, end_date: '2026-10-01' }));
const invalid = structuredClone(state); invalid.tasks[0].plan_id = 999999;
assert.throws(() => M.validate(invalid));
const duplicate = structuredClone(state); duplicate.completions.push({ ...duplicate.completions[0] });
assert.throws(() => M.validate(duplicate));
const mismatch = structuredClone(state); mismatch.executions[0].actual_minutes = 999;
assert.throws(() => M.validate(mismatch));
assert.equal(M.find(state, 'plans', plan).title, 'Changed plan');
apply('delete', { kind: 'execution', id: record });
assert.equal(M.summary(state, plan).values.actual, 0);
assert.equal(M.summary(state, plan).values.blocked, 0);
assert.deepEqual(M.validate(state), state);
console.log('PASS: immutable history, CRUD, duplicate completion/execution/next plan, Seoul dates, cohort sums, soft delete, safe restore and validation.');
